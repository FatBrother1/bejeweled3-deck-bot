"""闪电模式。

限时 1 分钟。和普通三消差两处：

# 一、时间宝石（要优先去消）

限时模式里不拿时间宝石就等着时间耗尽，所以求解器要优先去消它。标记是
`flags & 131072`（COUNTER 位），计数在 `Piece+0x244`，由内存后端每次读盘时
放进 `extra["timegems"]`；`solver_pro.rank_moves` 那边对踩到宝石的招加
+100000 权重（远大于普通得分 —— 时间比分数重要）。

# 二、棋盘几何跟经典不一样（这是 2026-09-26 修的那个 bug）

闪电的棋盘属于「现代版式」（格距 85.29），而且**原点比经典低得多**。
一直用经典几何（x0=476 y0=79 px=89.17 py=88.17）时，行中心差了 **31~47 像素
（超过半格）**：

    经典几何给出的行中心   79, 167, 255, 343, 432, 520, 608, 696
    闪电实测的行中心      126, 212, 298, 384, 469, 555, 641, 727

拖动落到隔壁行 ⇒ 游戏认为不是合法交换、原样弹回 ⇒ 棋盘纹丝不动，而 bot 还在
按自己的棋盘反复算同一招。实测那一局 113 步里 52 步被判被拒（46%），日志满屏
`✗拉黑` + `★ 合法走法全被拉黑 → 解禁重算`，就是用户看到的"空转和重复交换"。

标定法（与蝴蝶/牌局同一套）：抓一帧 + 用 reader_mem 读真实棋盘，网格搜
(x0, y0, px, py) 最大化「采样色 == 内存棋盘色」的格数。**注意分类器必须带
白宝石兜底**（白宝石低饱和，只用高饱和像素投票会把它读成红色），否则最优点
会被拉到错的位置。标定结果 64/64（x0=498.0 y0=126.0 px=85.286 py=85.9）。

# 三、怎么认出自己

两条判据，任一成立即认领：

  · **棋盘对象的 vtable 值**（`extra["board_vt"] == 0x8665C4`）—— 主判据。
    点进闪电模式那一刻它就变成这个值，跟 which_mode.py 里那条实测记录同源。
    为什么需要它：时间宝石**只在盘上待几秒**，光靠"有宝石"要等到第一个宝石
    出现才认得出，那几秒会拿经典几何去点，白送几步。
  · **盘上有时间宝石** —— 兜底，也是"值变了还报旧模式"时的保险。
"""
from .base import Mode as _Base

# [Board+0x0]（棋盘对象的 vtable 指针）实测值 → 模式，与 which_mode.py 的
# MEM_MAP 同源（那边是给插件面板看的，这里是给 bot 选几何用的）。
VT_LIGHTNING = 0x8665C4


class Mode(_Base):
    KEY = "lightning"
    NAME = "闪电"
    GEO = "lightning"
    EFFECTIVE = "score"
    GEO_WHY = ("  ← 闪电棋盘是『现代版式』且比经典低约 47px，"
               "用经典几何会点到隔壁行")

    def detect(self, ctx):
        extra = ctx["extra"] or {}
        if extra.get("board_vt") == VT_LIGHTNING:
            return True
        return bool(extra.get("timegems"))

    # ★ 2026-09-28（机制来自萌娘百科/17173 攻略）：时间宝石是「每颗下落的
    #   宝石按几率转化」⇒ 消除总量越大、出得越多；而特殊宝石（火焰炸 3×3、
    #   闪电清行列、暴烈极速下主动消除全部爆炸）是拉高单步消除量的主要手段。
    #   把 w_special 从默认 8.0 提到 10.0，让造/引特宝的招略微前置。
    #   只影响闪电模式；其它模式不传仍走 8.0。
    W_SPECIAL = 10.0

    def solver_kw(self):
        return dict(super().solver_kw(), w_special=self.W_SPECIAL)

    def on_board_info(self, ctx, tg, bf):
        if tg:
            ctx["log"]("  ⏱ 时间宝石 %d 个: %s"
                       % (len(tg), ", ".join("(%d,%d)+%d" % t for t in tg)))
